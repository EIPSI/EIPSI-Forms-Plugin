const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const assert=require('assert/strict');
const root=path.resolve(__dirname,'../..');
const contracts=require('./contracts.json');
const migrations=require('../m4/m3-boundary-migrations.json');
const m5Migrations=require('../m5/boundary-migrations.json');
const m6Migrations=require('../m6/boundary-migrations.json');
const m7Migrations=require('../m7/boundary-migrations.json');
const m8Migrations=require('../m8/boundary-migrations.json');
let count=0;
for(const [file,expected] of Object.entries(contracts.unchanged_files)) {
    const migration=migrations[file];
    if (migration) assert.equal(migration.m3_sha256,expected,'Original M3 baseline must remain recorded');
    const m4Expected=migration ? migration.m4_sha256 : expected;
    const m5Migration=m5Migrations[file];
    if (m5Migration) assert.equal(m5Migration.before_m5_sha256,m4Expected,'M4 boundary history must remain recorded');
    const beforeM6=m5Migration ? m5Migration.m5_sha256 : m4Expected;
    const m6Migration=m6Migrations[file];
    if(m6Migration) assert.equal(m6Migration.before_m6_sha256,beforeM6,'M5 history preserved');
    const beforeM7=m6Migration ? m6Migration.m6_sha256 : beforeM6;
    const m7Migration=m7Migrations[file];
    if(m7Migration) assert.equal(m7Migration.before_m7_sha256,beforeM7,'M6 history preserved');
    const beforeM8=m7Migration ? m7Migration.m7_sha256 : beforeM7;
    const m8Migration=m8Migrations[file];
    if(m8Migration) assert.equal(m8Migration.before_m8_sha256,beforeM8,'M7 history preserved');
    assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex'),m8Migration ? m8Migration.m8_sha256 : beforeM8,'Boundary changed beyond explicit M4 migration: '+file);
    console.log('PASS unchanged boundary '+file); count++;
}
const manifest=require('../../src/frontend/forms/manifest.json');
const source=manifest.entry_order.map(file=>fs.readFileSync(path.join(root,'src/frontend/forms',file),'utf8')).join('');
assert.equal(crypto.createHash('sha256').update(source).digest('hex'),manifest.baseline_sha256);
new Function(source);
new Function(fs.readFileSync(path.join(root,'assets/js/eipsi-forms.js'),'utf8'));
console.log('PASS classic composition, baseline hash and executable artifact');count++;
assert.equal(fs.existsSync(path.join(root,'src/frontend/eipsi-save-continue.js')),false,'Unused duplicate remains');
assert.ok(fs.existsSync(path.join(root,'assets/js/eipsi-save-continue.js')),'Active partial client deleted');
console.log('PASS conditioned purge retains active partial consumer');count++;
console.log(`${count} tests, 0 failures`);
